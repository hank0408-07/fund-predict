function probColor(p){
  const t=Math.max(0,Math.min(1,(p-50)/45));
  const r=Math.round(91+t*(255-91));
  const g=Math.round(157+t*(94-157));
  const b=Math.round(255+t*(126-255));
  return `rgb(${r},${g},${b})`;
}
